# mapeia (d3,d4,d5) do ISIC para rótulo fino em português + grupo amplo
def fine(d3, d4, d5):
    d4 = d4 or ""; d5 = d5 or ""
    if d3 == "Nevus":
        if "Dysplastic" in d5 or "Atypical" in d4 or "Clark" in d5: return "Nevo displásico (atípico)", "nevo"
        if "Congenital" in d4: return "Nevo congênito", "nevo"
        if "Lentiginous" in d4: return "Nevo lentiginoso", "nevo"
        if "Blue" in d4: return "Nevo azul", "nevo"
        if "Spitz" in d4 or "Reed" in d4: return "Nevo de Spitz ou Reed", "nevo"
        if "Recurrent" in d4: return "Nevo recorrente", "nevo"
        if "Combined" in d4: return "Nevo combinado", "nevo"
        return "Nevo melanocítico comum", "nevo"
    if d3 in ("Melanoma in situ", "Melanoma Invasive", "Melanoma, NOS"):
        if "Lentigo maligna" in d4 or "lentigo maligna" in d4: return "Lentigo maligno / melanoma lentigo maligno", "melanoma"
        if "Superficial spreading" in d4: return "Melanoma extensivo superficial", "melanoma"
        if "associated with a nevus" in d4 or "Associated with a nevus" in d4: return "Melanoma associado a nevo", "melanoma"
        if d3 == "Melanoma in situ": return "Melanoma in situ", "melanoma"
        return "Melanoma invasivo", "melanoma"
    if d3 == "Basal cell carcinoma":
        if "Superficial" in d4: return "CBC superficial", "cbc"
        if "Infiltrating" in d4 or "Sclerosing" in d4: return "CBC infiltrativo ou esclerodermiforme", "cbc"
        return "CBC (nodular ou subtipo não informado)", "cbc"
    if d3 == "Squamous cell carcinoma in situ": return "CEC in situ (doença de Bowen)", "cec"
    if d3 == "Squamous cell carcinoma, Invasive" and "Keratoacanthoma" in d4: return "Ceratoacantoma (CEC tipo ceratoacantoma)", "cec"
    if d3.startswith("Squamous cell carcinoma"): return "Carcinoma espinocelular (CEC) invasivo", "cec"
    if d3 == "Solar or actinic keratosis": return ("Ceratose actínica hipertrófica" if "Hypertrophic" in d4 else "Ceratose actínica"), "ceratose_actinica"
    if d3 == "Seborrheic keratosis": return "Queratose seborreica", "queratose_seborreica"
    if d3 == "Dermatofibroma": return "Dermatofibroma", "dermatofibroma"
    if d3 == "Hemangioma": return "Hemangioma", "vascular"
    if d3 in ("Angiokeratoma", "Pyogenic granuloma"): return "Angioqueratoma ou granuloma piogênico", "vascular"
    if d3 == "Lichen planus like keratosis": return "Queratose liquenoide", "outras"
    if d3 == "Fibroepithelial polyp": return "Pólipo fibroepitelial", "outras"
    if d3 in ("Solar lentigo", "Lentigo NOS", "Lentigo simplex"): return "Lentigo (solar ou simples)", "outras"
    if d3 == "Verruca": return "Verruga viral", "outras"
    return "Outras (cicatriz, neurofibroma, hiperplasia sebácea e raras)", "outras"
